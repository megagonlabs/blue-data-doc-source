# Question 1 — find all mentions of Acme Corp
# ---------------------------------------------------------------------------

def q1_entity_lookup(pipeline: DocumentPipeline,
                     fname_map: dict[str, str]) -> None:
    _section("Question 1 — Find every mention of Acme Corp across all documents")

    _hr()
    _label("Attempt A — BM25 keyword search  (k=4 cap)")
    _label("")
    _label("  pipeline.search('Acme Corp', mode='bm25', k=4)")
    _label("")
    _label("  Problem: k=4 caps the result set. Acme Corp appears in 6 documents")
    _label("  producing multiple chunks — BM25 will silently drop some.")
    _label("")

    bm25_hits = pipeline.search("Acme Corp", mode="bm25", k=4, collection=COLLECTION)
    docs_in_bm25 = {r.get("document_id") for r in bm25_hits
                    if "acme corp" in r.get("text", "").lower()}
    print(f"    BM25 returned {len(bm25_hits)} chunk(s) from "
          f"{len(docs_in_bm25)} distinct document(s)  [k=4 cap]")
    for r in bm25_hits:
        _chunk_hit("hit", r, fname_map)
    print()

    _hr()
    _label("Attempt B — graph traversal  (O(1), no k limit)")
    _label("")
    _label("  pipeline.graph_neighbors('Acme Corp')")
    _label("")
    _label("  Resolves entity:PROPER_NOUN:acme corp → MENTIONS edges → Chunks.")
    _label("  Returns every chunk across every document. No scoring. No k cap.")
    _label("")

    graph_hits = pipeline.graph_neighbors("Acme Corp", k=999)
    doc_ids    = {r["document_id"] for r in graph_hits}
    print(f"    Graph returned {len(graph_hits)} chunk(s) across "
          f"{len(doc_ids)} document(s)  [no cap]")
    for r in graph_hits:
        _chunk_hit("hit", r, fname_map)
    print()
    missing = len(doc_ids) - len(docs_in_bm25)
    if missing > 0:
        print(f"    ↑ Graph found {missing} more document(s) than BM25 with k=4.")
    print()



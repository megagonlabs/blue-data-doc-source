# Question 2 — documents mentioning BOTH Sarah Chen AND Acme Corp
# ---------------------------------------------------------------------------

def q2_entity_intersection(pipeline: DocumentPipeline,
                            fname_map: dict[str, str]) -> None:
    _section("Question 2 — Which documents mention BOTH Sarah Chen AND Acme Corp?")

    _hr()
    _label("Attempt A — two separate BM25 searches + manual intersection")
    _label("")
    _label("  hits_a = pipeline.search('Sarah Chen', mode='bm25', k=4)")
    _label("  hits_b = pipeline.search('Acme Corp',  mode='bm25', k=4)")
    _label("  shared = doc_ids_with_exact_match(hits_a) & doc_ids_with_exact_match(hits_b)")
    _label("")
    _label("  Problem: k=4 caps each result set independently. A document where")
    _label("  Sarah Chen appears only in chunk 5 (past the cap) is silently excluded.")
    _label("  Correctness depends on choosing k large enough — you rarely know this")
    _label("  in advance for a growing corpus.")
    _label("")

    hits_a = pipeline.search("Sarah Chen", mode="bm25", k=4, collection=COLLECTION)
    hits_b = pipeline.search("Acme Corp",  mode="bm25", k=4, collection=COLLECTION)
    docs_a = {r["document_id"] for r in hits_a
              if "sarah chen" in r.get("text", "").lower()}
    docs_b = {r["document_id"] for r in hits_b
              if "acme corp"  in r.get("text", "").lower()}
    shared_search = docs_a & docs_b
    print(f"    BM25 — Sarah Chen exact hits: {len(docs_a)} doc(s)  [k=4]")
    print(f"    BM25 — Acme Corp  exact hits: {len(docs_b)} doc(s)  [k=4]")
    print(f"    Intersection: {len(shared_search)} doc(s)")
    for doc_id in sorted(shared_search):
        print(f"      {fname_map.get(doc_id, doc_id)}")
    print()

    _hr()
    _label("Attempt B — graph entity intersection  (complete at any corpus size)")
    _label("")
    _label("  sc_chunks = pipeline.graph_neighbors('Sarah Chen', k=999)")
    _label("  ac_chunks = pipeline.graph_neighbors('Acme Corp',  k=999)")
    _label("  both      = {c['document_id'] for c in sc_chunks}")
    _label("            & {c['document_id'] for c in ac_chunks}")
    _label("")

    sc_hits   = pipeline.graph_neighbors("Sarah Chen", k=999)
    ac_hits   = pipeline.graph_neighbors("Acme Corp",  k=999)
    sc_docs   = {r["document_id"] for r in sc_hits}
    ac_docs   = {r["document_id"] for r in ac_hits}
    both_docs = sc_docs & ac_docs

    print(f"    Sarah Chen appears in: {len(sc_docs)} document(s)")
    print(f"    Acme Corp  appears in: {len(ac_docs)} document(s)")
    print(f"    Both appear in       : {len(both_docs)} document(s) — complete")
    print()
    for doc_id in sorted(both_docs):
        print(f"      ✓  {fname_map.get(doc_id, doc_id)}")
    print()
    _label("  One intersection. No k risk. Scales to any corpus size.")
    print()



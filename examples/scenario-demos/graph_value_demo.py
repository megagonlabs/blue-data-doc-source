# Question 3 — expand context around a graph hit using NEXT/PREV
# ---------------------------------------------------------------------------

def q3_context_expansion(pipeline: DocumentPipeline,
                          graph: MemoryGraphSource,
                          fname_map: dict[str, str]) -> None:
    _section("Question 3 — Show context around the Acme Corp incident finding")

    # Find the chunk in incident_0088 that mentions Acme Corp (root cause section)
    acme_hits = pipeline.graph_neighbors("Acme Corp", k=999)
    target    = next(
        (r for r in acme_hits
         if fname_map.get(r["document_id"], "").startswith("incident_0088")
         and "vendor" in r.get("text_preview", "").lower()),
        None,
    )
    if target is None:
        # fallback: any incident_0088 chunk
        target = next(
            (r for r in acme_hits
             if fname_map.get(r["document_id"], "").startswith("incident_0088")),
            None,
        )
    if target is None:
        print("  (incident_0088 not found in graph — skipping)")
        return

    target_chunk_id  = target["chunk_id"]
    target_node_id   = f"chunk:{target_chunk_id}"
    target_fname     = fname_map.get(target["document_id"], target["document_id"])
    target_prev      = target.get("text_preview", "").replace("\n", " ").strip()[:75]

    _hr()
    _label(f"  Found via graph_neighbors('Acme Corp'):")
    _label(f"  File   : {target_fname}")
    _label(f"  Chunk  : {target_chunk_id}")
    _label(f"  Text   : {target_prev!r}…")
    print()

    _hr()
    _label("Attempt A — re-query with an expanded keyword string")
    _label("")
    _label("  pipeline.search('Acme Corp freezer incident compressor warranty', mode='bm25', k=4)")
    _label("")
    _label("  Problem: BM25 ranks by term overlap across the FULL corpus.")
    _label("  Chunks from incident_0091 (HVAC failure) score similarly and")
    _label("  appear in the results — even though you only want context from")
    _label("  incident_0088. Reading order within the document is ignored.")
    _label("")

    bm25_ctx = pipeline.search(
        "Acme Corp freezer incident compressor warranty",
        mode="bm25", k=4, collection=COLLECTION,
    )
    print(f"    BM25 returned {len(bm25_ctx)} chunk(s):")
    for r in bm25_ctx:
        _chunk_hit("hit", r, fname_map)
    other_docs = [r for r in bm25_ctx
                  if not fname_map.get(r.get("document_id", ""), "").startswith("incident_0088")]
    if other_docs:
        print()
        print(f"    ↑ {len(other_docs)} chunk(s) came from OTHER documents — context pollution.")
    print()

    _hr()
    _label("Attempt B — walk NEXT / PREV from the target chunk")
    _label("")
    _label(f"  Resolving PREV → THIS → NEXT for {target_node_id}")
    _label("")
    _label("  All neighbours are from the same document, in reading order.")
    _label("  No query. No scoring. No other documents involved.")
    _label("")

    prev_items = graph.get_neighbors("documents", target_node_id,
                                     edge_type="PREV", direction="out")
    next_items = graph.get_neighbors("documents", target_node_id,
                                     edge_type="NEXT", direction="out")

    def _node_text(items: list[dict], fallback: str) -> str:
        if not items:
            return fallback
        props  = items[0]["node"].get("properties", {})
        text   = props.get("text_preview", "").replace("\n", " ").strip()
        return text[:120] if text else fallback

    prev_text = _node_text(prev_items, "(start of document)")
    next_text = _node_text(next_items, "(end of document)")

    print(f"    ← PREV  [{target_fname}]")
    print(f"      {prev_text!r}…")
    print()
    print(f"    ● THIS  [{target_fname}]  ← Acme Corp mention found here")
    print(f"      {target_prev!r}…")
    print()
    print(f"    → NEXT  [{target_fname}]")
    print(f"      {next_text!r}…")
    print()
    _label("  The analyst can now read the incident timeline in sequence:")
    _label("  what happened before the Acme Corp mention, and what follow-up")
    _label("  actions were assigned after it — all from the same document,")
    _label("  in the order they were written.")
    print()



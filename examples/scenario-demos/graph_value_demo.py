"""
Graph Backend — Why It Beats Vector Search for Entity Questions
==============================================================
Scenario: a compliance analyst has six documents — contracts, vendor
agreements, and incident reports — all mentioning overlapping people
and organisations. Three realistic questions are posed. Each is answered
first with keyword/vector search (shows the limitation), then with graph
traversal (shows the solution).

Question 1 — "Find everything connected to Acme Corp across all docs"
  Search: BM25 keyword scan with k=4 — caps the result set, missing
          documents where Acme Corp appears beyond the k limit.
  Graph:  O(1) lookup via entity node → MENTIONS edges → every mention
          across every document, no k limit, no false positives.

Question 2 — "Which documents mention BOTH Sarah Chen AND Acme Corp?"
  Search: two separate BM25 queries + manual intersection — k-limited,
          fragile, requires application-level set logic.
  Graph:  intersect the neighbour sets of two entity nodes directly.
          One operation, exact answer, complete at any corpus size.

Question 3 — "Show context around the Acme Corp incident finding"
  Search: re-query with an expanded string — returns chunks from other
          documents ranked by keyword overlap, not by reading position.
  Graph:  walk NEXT/PREV from the target chunk — deterministic reading-
          order expansion, same document only, zero embedding calls.

No API key required. No Redis required. Runs entirely in-process.

Run:
    python3 examples/scenario-demos/graph_value_demo.py
"""

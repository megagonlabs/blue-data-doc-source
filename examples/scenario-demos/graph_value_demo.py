def summary() -> None:
    _section("Summary — when graph traversal outperforms keyword/vector search")
    print(f"  {'Question':<40} {'Search':<32} {'Graph'}")
    _hr()
    rows = [
        ("Exact entity lookup across corpus",
         "BM25/KNN — k-capped, may miss docs",
         "O(1) via MENTIONS — exact, no cap"),
        ("Docs mentioning entity A AND B",
         "Two queries + intersect (k-limited)",
         "Neighbour intersection — complete"),
        ("Reading-order context expansion",
         "Re-query — cross-doc noise",
         "NEXT/PREV — same doc, in order"),
    ]
    for q, s, g in rows:
        print(f"  {q:<40} {s:<32} {g}")
    print()
    print("  Graph traversal complements — not replaces — vector search:")
    print()
    print("    Vector/BM25:  'find chunks about cost-sharing arrangements'")
    print("    Graph:        'find every chunk naming Acme Corp'")
    print("    Graph:        'which docs mention both Sarah Chen and Acme Corp?'")
    print("    Graph:        'show me what comes before and after this finding'")
    print()
    print("  Combined:  DOCUMENT.FIND_THEN_SEARCH filters documents by entity")
    print("  or extracted field first, then runs vector search only within")
    print("  the matched documents — best of both in a single call.")
    print()



    print("  Backend : MemoryGraphSource (in-process, no infra required)")
    print()
    print("  Each question answered two ways:")
    print("    Attempt A — keyword/BM25 search  (shows the limitation)")
    print("    Attempt B — graph traversal        (shows the solution)")

    pipeline, graph = build_pipeline()

    print()
    _hr()
    print("Ingesting corpus …")
    _hr()
    fname_map = ingest_corpus(pipeline)

def _hr() -> None:
    print(DIV2)


def _section(title: str) -> None:
    print()
    print(DIV)
    print(f"  {title}")
    print(DIV)
    print()


def _label(text: str) -> None:
    print(f"  {text}")


def _chunk_hit(label: str, chunk: dict, fname_map: dict[str, str]) -> None:
    doc_id  = chunk.get("document_id", "")
    fname   = chunk.get("file_name") or fname_map.get(doc_id, doc_id)
    section = f"[{chunk['section_title']}] " if chunk.get("section_title") else ""
    preview = chunk.get("text", chunk.get("text_preview", ""))
    preview = preview.replace("\n", " ").strip()[:75]
    print(f"    {label}: {fname}  {section}{preview!r}…")


def build_pipeline() -> tuple[DocumentPipeline, MemoryGraphSource]:
    graph    = MemoryGraphSource("compliance")
    pipeline = DocumentPipeline(
        embedding_model=DummyEmbeddingModel(dim=8),
        vector_source=LocalMemoryVectorStore(),
        enricher=BasicEnricher(),
        graph_source=graph,
        graph_database="documents",
        chunk_size=120,
        overlap=20,
        collection=COLLECTION,
    )
    pipeline.ensure_index(COLLECTION)
    return pipeline, graph


def ingest_corpus(pipeline: DocumentPipeline) -> dict[str, str]:
    """Returns mapping of document_id → file_name."""
    doc_id_to_fname: dict[str, str] = {}
    for fname, text in DOCS.items():
        chunks = pipeline.ingest_text(text, file_name=fname)
        if chunks:
            doc_id_to_fname[chunks[0]["document_id"]] = fname
    return doc_id_to_fname


